function stickerRange(start, end) {
  return Array.from({ length: end - start + 1 }, (_, index) => start + index);
}

function group(packId, label, stickerNumbers) {
  return {
    packId,
    label,
    stickerIds: stickerNumbers.map((number) => `${packId}-${number}`),
  };
}

